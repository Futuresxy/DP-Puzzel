"""Freeze the selected nine-ratio cost evidence for the Chinese working draft."""
import csv
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PAPER = ROOT / "paper"
SOURCES = (
    "paper/data/DP_area_power/ratio4_costs.csv",
    "hw/power/records/first_three_vs_v19_baseline_20261112.csv",
    "hw/dc_syn/records/t8h16q96e192_v112_20261112.json",
)
ORDER = ("1:2:4", "1:2:6", "1:2:8", "1:4:4", "1:4:8",
         "1:2:12", "1:2:16", "1:6:12", "1:8:16")
MODES = ("bf16", "mxfp8_e4m3", "mxfp4_e2m1")


def collect_evidence():
    records = {ratio: dict(ratio=ratio, area_um2=None,
                          power_total_mw={mode: None for mode in MODES},
                          sources=[], status="pending") for ratio in ORDER}
    with (ROOT / SOURCES[0]).open() as stream:
        for row in csv.DictReader(stream):
            record = records[row["ratio"]]
            record.update(area_um2=float(row["area_um2"]), status="area_and_power")
            record["power_total_mw"] = {
                mode: float(row[mode + "_total_mw"]) for mode in MODES}
            record["sources"].append(SOURCES[0])
    ratio_by_top = {"dp_top_t8h16q64e64": "1:4:4",
                    "dp_top_t8h16q32e192": "1:2:12",
                    "dp_top_t8h16q32e256": "1:2:16"}
    with (ROOT / SOURCES[1]).open() as stream:
        for row in csv.DictReader(stream):
            record = records[ratio_by_top[row["top"]]]
            record.update(area_um2=float(row["area_um2"]), status="area_and_power")
            record["power_total_mw"][row["format"]] = float(row["total_mw"])
            record["sources"] = [SOURCES[1]]
            record["dc_run"] = row["dc_run"]
            record["power_run"] = row["campaign"]
    qe = json.loads((ROOT / SOURCES[2]).read_text())["records"][0]
    assert qe["top"] == "dp_top_t8h16q96e192" and qe["result"]["flow_pass"]
    records["1:6:12"].update(area_um2=qe["result"]["total_area_um2"],
        status="area_only", sources=[SOURCES[2]], dc_run=qe["run"],
        verification_id=qe["verification_id"])
    baseline = records["1:2:4"]
    for record in records.values():
        record["area_ratio"] = (record["area_um2"] / baseline["area_um2"]
                                if record["area_um2"] is not None else None)
    evidence = dict(schema_version=1, date="2026-11-12", scope="DP only, post-synthesis, pre-CTS/pre-route",
        condition=dict(process="N12", corner="TT", voltage_v=0.7, temperature_c=85,
                       frequency_hz=1_000_000_000, clock_gating=True),
        sources={p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in SOURCES},
        selection_policy="Explicit snapshot; missing measurements remain null. No automatic latest-run discovery.",
        limits=["Qwen3-8B activity, not DeepSeek power measurement",
                "E256 expands combinational alignment hierarchy; source reports retain strategy differences",
                "1:6:12 power and 1:8:16 costs pending in this selection"],
        records=list(records.values()))
    (PAPER / "data/evidence/ratio9_costs_20261112.json").write_text(
        json.dumps(evidence, indent=2, ensure_ascii=False) + "\n")
    return evidence


def render_table(evidence):
    records = {record["ratio"]: record for record in evidence["records"]}
    assert tuple(records) == ORDER
    baseline = records["1:2:4"]
    lines = ["% Generated by scripts/build_ratio9_table.py; missing evidence is not zero.",
             r"\begin{tabular}{@{}lrrrrr@{}}\toprule",
             r"H:Q:E & $A$ ($\mu$m$^2$) & $A/A_0$ & $P_H$ & $P_Q$ & $P_E$ \\\midrule"]
    for record in records.values():
        area = "待补" if record["area_um2"] is None else f"{record['area_um2']:.0f}"
        ratio = "--" if record["area_ratio"] is None else f"{record['area_ratio']:.2f}"
        powers = ["待补" if record["power_total_mw"][mode] is None
                  else f"{record['power_total_mw'][mode]:.2f}" for mode in MODES]
        lines.append(" & ".join(["$" + record["ratio"] + "$", area, ratio, *powers]) + r" \\")
    lines.append(r"\bottomrule\end{tabular}")
    (PAPER / "tables/ratio9_costs.tex").write_text("\n".join(lines) + "\n")
    for ratio in ("1:2:8", "1:2:16", "1:4:4"):
        r = records[ratio]
        print(ratio, "area", r["area_ratio"], "H/Q/E power ratios",
              [r["power_total_mw"][m] / baseline["power_total_mw"][m] for m in MODES])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh-evidence", action="store_true",
                        help="Explicitly re-import the selected source reports; otherwise use the retained snapshot")
    args = parser.parse_args()
    evidence = (collect_evidence() if args.refresh_evidence else json.loads(
        (PAPER / "data/evidence/ratio9_costs_20261112.json").read_text()))
    render_table(evidence)
