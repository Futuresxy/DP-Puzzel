"""Recompute fixed-area deployment, prefill work, simplex regions and paper tables.

Inputs are editable local JSON. Outputs are analytical compute-only estimates;
DP activity power is a proxy, not measured DeepSeek or whole-chip energy.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import sys

import numpy as np
from costs import FORMATS, deploy, evaluate, mapped_work
import workloads
from simplex import workload_grid, winner_regions, robust_energy_regions
from plot_triangles import redraw

ROOT = Path(__file__).resolve().parents[1]


def table(path, spec, headers, rows):
    body = '\n'.join(' & '.join(map(str, row)) + r' \\' for row in rows)
    path.write_text('% Generated by scripts/reproduce.py.\n'
                   + r'\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}' + spec + r'@{}}\toprule' + '\n'
                   + ' & '.join(headers) + r' \\\midrule' + '\n' + body
                   + '\n' + r'\bottomrule\end{tabular*}' + '\n')


def names(values, ratios):
    return '|'.join(r for r, v in zip(ratios, values)
                    if np.isclose(v, min(values), rtol=1e-10, atol=0))


def positive_int(value):
    return type(value) is int and value > 0


def run(config_path, output):
    config_path = config_path.resolve()
    cfg = json.loads(config_path.read_text())
    for field in ('baseline_cores', 'array_m', 'array_n', 'batch', 'simplex_divisions'):
        if not positive_int(cfg[field]):
            raise ValueError(f'{field} must be a positive integer')
    if not 0 < cfg['tensor_area_fraction'] <= 1 or cfg['peripheral_growth'] < 0:
        raise ValueError('Invalid tensor fraction or peripheral growth')
    contexts = cfg['contexts']
    if not contexts or any(not positive_int(s) for s in contexts) or contexts != sorted(set(contexts)):
        raise ValueError('contexts must be increasing unique positive integers')
    supported = ['DeepSeek-V4-Flash', 'DeepSeek-V4-Pro', 'DeepSeek-V4.1-Flash']
    if not cfg['models'] or len(set(cfg['models'])) != len(cfg['models']) or any(m not in supported for m in cfg['models']):
        raise ValueError('Select distinct supported DeepSeek models')
    hp = (config_path.parent / cfg['hardware']).resolve()
    hardware_input = json.loads(hp.read_text())
    raw = hardware_input['designs']
    power_assumptions = hardware_input.get('power_assumptions', {})
    ratios = [h['ratio'] for h in raw]
    if ratios != ['1:2:4', '1:2:6', '1:2:8', '1:4:8']:
        raise ValueError('This paper compares four ordered ratios with 1:2:4 baseline')
    dp_count = cfg['array_m'] * cfg['array_n']
    hardware = []
    for h in raw:
        capacity, power = [], []
        if not np.isfinite(h['area_um2']) or h['area_um2'] <= 0:
            raise ValueError('Area must be finite and positive')
        for f in FORMATS:
            p, k = h['power'][f], h['macs_cycle'][f]
            if not positive_int(k) or not np.isfinite([p['total_mw'], p['frequency_mhz']]).all() or min(p['total_mw'], p['frequency_mhz']) <= 0:
                raise ValueError('Measured power, frequency and MAC/cycle must be positive')
            capacity.append(dp_count * 2*k*p['frequency_mhz']/1e6)
            power.append(dp_count*p['total_mw']/1000)
        hardware.append(dict(ratio=h['ratio'], area=dp_count*h['area_um2']/1e6,
                             capacity=np.array(capacity), power=np.array(power)))
    # E combines MX/NV only if their throughput is equal; energy remains separate.
    if any(not np.isclose(h['capacity'][2], h['capacity'][3], rtol=1e-12) for h in hardware):
        raise ValueError('Three-axis throughput requires equal MXFP4 and NVFP4 peak rates')
    designs = deploy(hardware, alpha=cfg['tensor_area_fraction'], growth=cfg['peripheral_growth'],
                     baseline_cores=cfg['baseline_cores'], integer=True)
    continuous = deploy(hardware, alpha=cfg['tensor_area_fraction'], growth=cfg['peripheral_growth'],
                        baseline_cores=cfg['baseline_cores'])
    if any(d['count'] < 1 for d in designs):
        raise ValueError('Area budget cannot fit at least one core of every candidate')
    baseline_area = hardware[0]['area']/cfg['tensor_area_fraction']
    budget = cfg['baseline_cores'] * baseline_area
    other = baseline_area-hardware[0]['area']
    for d in designs:
        assert d['count']*d['area'] <= budget+1e-10 < (d['count']+1)*d['area']
    out = output/'data/results'; figures = output/'figures'; tables = output/'tables'
    for folder in (out, figures, tables): folder.mkdir(parents=True, exist_ok=True)
    hw_rows = []
    for h, d, c, raw_h in zip(hardware, designs, continuous, raw):
        row = dict(ratio=h['ratio'], dp_area_um2=raw_h['area_um2'], array_area_mm2=h['area'],
                   core_area_mm2=d['area'], other_area_mm2=d['area']-h['area'],
                   budget_mm2=budget, continuous_cores=c['count'], integer_cores=int(d['count']),
                   remaining_area_mm2=budget-d['count']*d['area'])
        for i, f in enumerate(FORMATS):
            for name, values in [('array_tflops', h['capacity']), ('array_w', h['power']),
                                  ('pool_tflops', d['capacity']), ('pool_w', d['power'])]:
                row[f+'_'+name] = values[i]
        hw_rows.append(row)
    workloads.write_csv(out/'core_counts_compute_power.csv', hw_rows)
    cap = np.array([d['capacity'] for d in designs])
    power = np.array([d['power'] for d in designs])
    cost4 = power/cap
    np.testing.assert_allclose(cost4, [h['power']/h['capacity'] for h in hardware])
    coeff = dict(time=1/cap[:, :3], energy=cost4[:, :3])
    regions = {key:winner_regions(c) for key, c in coeff.items()}
    robust = robust_energy_regions(cost4[:, :3], cost4[:, [0, 1, 3]])
    grid = workload_grid(cfg['simplex_divisions']); sweep = []
    for obj, c in coeff.items():
        for x, values in zip(grid, grid@c.T):
            sweep.append(dict(objective=obj, x_H=x[0], x_Q=x[1], x_E=x[2], winner=names(values,ratios),
                              **{r:v for r,v in zip(ratios,values)}))
        for region in regions[obj]:
            if region['fraction'] > 1e-10:
                values = np.array(region['vertices_hqe'])@c.T
                assert np.all(values[:,region['index']] <= values.min(axis=1)+1e-9)
    workloads.write_csv(out/'simplex_sweep.csv', sweep)
    (out/'regions.json').write_text(json.dumps(dict(**regions,
        time_continuous=winner_regions(1/np.array([d['capacity'][:3] for d in continuous]))),indent=2)+'\n')
    (out/'energy_encoding_regions.json').write_text(json.dumps(dict(
        evidence_scope='conditional_on_input_power_assumptions', power_assumptions=power_assumptions,
        mx_only=regions['energy'],
        nv_only=winner_regions(cost4[:,[0,1,3]]),encoding_independent=robust),indent=2)+'\n')
    all_points = {}
    for profile, prefix in [('reference_work',''), ('nvfp4_experts','nvfp4_')]:
        points, evaluations, ledger = [], [], []
        for model in cfg['models']:
            for context in contexts:
                f, excluded, rows = mapped_work(model, 'prefill', context, profile, cfg['batch'])
                total = sum(f); x = np.array([f[0],f[1],f[2]+f[3]])/total
                t, e = evaluate(designs, f)
                pid = f'{model}/prefill/{context}' + ('/nvfp4_experts' if prefix else '')
                point = dict(point_id=pid,model=model,phase='prefill',context_tokens=context,batch=cfg['batch'],
                             x_H=x[0],x_Q=x[1],x_E=x[2],total_hqe_flops=int(total),
                             BF16_flops=int(f[0]),FP8_flops=int(f[1]),MXFP4_flops=int(f[2]),NVFP4_flops=int(f[3]),
                             excluded_FP32_flops=int(excluded),HQE_coverage=total/(total+excluded),
                             rho_NV_in_E=f[3]/sum(f[2:]) if sum(f[2:]) else 0.,
                             fastest=names(t,ratios),least_energy=names(e,ratios),
                             speedup_148=t[0]/t[3],energy_saving_148=1-e[3]/e[0])
                points.append(point)
                ledger.extend(dict(point_id=pid,**row) for row in rows)
                for j, ratio in enumerate(ratios):
                    evaluations.append(dict(point_id=pid,ratio=ratio,time_s=t[j],energy_j=e[j],
                                            effective_tflops=total/t[j]/1e12,average_dp_w=e[j]/t[j]))
        workloads.write_csv(out/(prefix+'prefill_points.csv'),points)
        workloads.write_csv(out/(prefix+'prefill_evaluations.csv'),evaluations)
        workloads.write_csv(out/(prefix+'kernel_ledger.csv.gz'),ledger)
        all_points[profile]=points
    ref, nv = all_points.values()
    for r,n in zip(ref,nv):
        assert r['BF16_flops']==n['BF16_flops'] and r['MXFP4_flops']==n['MXFP4_flops']
        assert r['FP8_flops']==n['FP8_flops']+n['NVFP4_flops']
        assert r['total_hqe_flops']==n['total_hqe_flops']
    table(tables/'hardware_compact_table.tex','lrrcc',
          ['Ratio',r'$A_C$',r'$n$',r'$C_H/C_Q/C_E$',r'$P_H/P_Q/P_E$'],
          [[f'${d["ratio"]}$',f'{d["area"]:.3f}',int(d['count']),
            '/'.join(f'{v:.1f}' for v in d['capacity'][:3]),
            '/'.join(f'{v:.1f}' for v in d['power'][:3])] for d in designs])
    def context_label(n):
        return f'{n//1048576}M' if n%1048576==0 else f'{n//1024}K' if n%1024==0 else str(n)
    table(tables/'prefill_compact_table.tex','llcrr',
          ['Model',r'$S$',r'$x_H/x_Q/x_E$ (\%)','Speedup',r'$\Delta E$ (\%)'],
          [[p['model'].replace('DeepSeek-',''),context_label(p['context_tokens']),
            '/'.join(f'{100*p[k]:.2f}' for k in ('x_H','x_Q','x_E')),
            f'{p["speedup_148"]:.3f}',f'{100*p["energy_saving_148"]:.2f}']
           for p in ref if p['context_tokens'] in (contexts[0],contexts[-1])])
    continuous_regions = winner_regions(1/np.array([d['capacity'][:3] for d in continuous]))
    table(tables/'region_table.tex','lrrr',
          ['Ratio','Time (cont.)','Time (int.)','DP energy'],
          [[f'${r}$',*[f'{group[j]["fraction"]*100:.2f}\\%' for group in
            (continuous_regions,regions['time'],regions['energy'])]] for j,r in enumerate(ratios)])
    redraw(out, figures, models=cfg['models'], ratios=ratios)
    inputs = [config_path,hp]+[workloads.SOURCE/m/'inference/config.json' for m in cfg['models']]
    def digest(p):return hashlib.sha256(p.read_bytes()).hexdigest()
    manifest = dict(status='analytical_compute_only',configuration=cfg,area_budget_mm2=budget,
                    power_assumptions=power_assumptions,
                    power_evidence={h['ratio']:{f:h['power'][f].get('evidence_status','unspecified')
                                               for f in FORMATS} for h in raw},
                    integer_cores=[int(d['count']) for d in designs],model_points=len(ref)+len(nv),
                    energy_scope='DP active power only; excludes peripheral, memory, communication and stalls',
                    inputs=[dict(path=str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else p.name,sha256=digest(p)) for p in inputs],
                    scripts=[dict(path=str(p.relative_to(ROOT)),sha256=digest(p)) for p in sorted((ROOT/'scripts').glob('*.py'))],
                    python=sys.version.split()[0],numpy=np.__version__)
    (out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps({k:manifest[k] for k in ('area_budget_mm2','integer_cores','model_points')},indent=2))


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config',type=Path,default=ROOT/'data/inputs/experiment.json')
    parser.add_argument('--output',type=Path,default=ROOT,help='Independent output root; default updates this paper figures/tables')
    args=parser.parse_args()
    run(args.config,args.output.resolve())
