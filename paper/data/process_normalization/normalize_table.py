#!/usr/bin/env python3
"""Render normalized efficiency values while retaining native data for audit."""
import csv
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
PROFILES = (
    ('1:2:4', 'dp_top'),
    ('1:2:6', 'dp_top_t8h16q32e96'),
    ('1:2:8', 'dp_top_t8h16q32e128'),
    ('1:4:8', 'dp_top_t8h16q64e128_opt'),
    ('0:0:4', 'dp_top_e64'),
    ('0:2:4', 'dp_top_q32e64'),
)
FORMATS = (('BF16', 'bf16'), ('MXFP8', 'mxfp8_e4m3'), ('MXFP4', 'mxfp4_e2m1'))
UNSUPPORTED_MODES = {
    'dp_top_e64': {'bf16', 'mxfp8_e4m3'},
    'dp_top_q32e64': {'bf16'},
}


def scale_factors(node, coefficients):
    if node == 12:
        return dict(area=1., delay=1., energy=1.)
    source, target = coefficients[str(node)], coefficients['14']
    if node == 7:
        # Invert the same rounded 14->7 factors used in the earlier analysis.
        return {key: 1 / round(target[key] / source[key], 3) for key in source}
    return {key: round(source[key] / target[key], 3) for key in source}


def replace_block(text, name, lines):
    begin = text.index('% BEGIN GENERATED ' + name)
    first = text.index('\n', begin)
    last = text.index('% END GENERATED ' + name, first)
    return text[:first + 1] + '\n'.join(lines) + '\n' + text[last:]


def profile_cells(points):
    values = {(point['config'], point['format']): point['value'] for point in points}
    best = {label: max(point['value'] for point in points if point['format'] == label)
            for label, _ in FORMATS}
    cells = []
    for index, (ratio, _) in enumerate(PROFILES):
        lines = []
        for label, _ in FORMATS:
            value = values.get((ratio, label))
            formatted = '---' if value is None else f'{value:.3f}'
            if value == best[label]:
                formatted = r'\textbf{' + formatted + '}'
            lines.append(label + ' & ' + formatted if index == 0 else formatted)
        macro = r'\Eff' if index == 0 else r'\Vals'
        cells.append(macro + '{' + r'\\'.join(lines) + '}')
    return cells


def main():
    inputs_path = HERE / 'table_inputs.json'
    inputs = json.loads(inputs_path.read_text())
    power_path = ROOT / 'paper/data/DP_area_power/latest6_power.csv'
    with power_path.open() as stream:
        measured = {(r['top'], r['format']): r for r in csv.DictReader(stream)}
    ours = next(w for w in inputs['works'] if w['id']=='ours')
    profile_areas = []
    for ratio, top in PROFILES:
        profile_points = [(label, measured[top, mode]) for label, mode in FORMATS
                          if mode not in UNSUPPORTED_MODES.get(top, ())]
        areas = {float(row['area_um2']) for _, row in profile_points}
        if len(areas) != 1:
            raise ValueError(f'Inconsistent area for {top}')
        area = areas.pop()
        profile_areas.append(f'{area:,.2f}'.replace(',', r'\,'))
        for label, row in profile_points:
            throughput_gflops = 2 * int(row['logical_k'])  # Measured at 1 GHz.
            ours['area'].append(dict(format=label, config=ratio, value=1000 * throughput_gflops / area))
            ours['energy'].append(dict(format=label, config=ratio, value=throughput_gflops / float(row['total_mw'])))
    rows, cells, factors = [], {'area':[], 'energy':[]}, {}
    for work in inputs['works']:
        factor = scale_factors(work['node'], inputs['coefficient_nodes'])
        factors[str(work['node'])] = factor
        for metric in ('area','energy'):
            gain = factor['area'] * factor['delay'] if metric == 'area' else factor['energy']
            grouped = {}
            for point in work[metric]:
                raw = point['value']; normalized = raw * gain
                rows.append(dict(work=work['id'], node_nm=work['node'], metric=metric,
                                 format=point['format'], config=point.get('config',''),
                                 native=raw, proxy12=normalized, efficiency_multiplier=gain))
                grouped.setdefault(point['format'], []).append('{:.3f}'.format(normalized))
            if work is ours:
                cells[metric].extend(profile_cells(work[metric]))
            else:
                lines = [label+' & '+' / '.join(values) for label, values in grouped.items()]
                cells[metric].append(r'\Eff{' + r'\\'.join(lines) + '}' if lines else '---')
    output = [r'% Generated by paper/data/process_normalization/normalize_table.py.']
    for metric, heading, unit in [('energy','Energy efficiency','TFLOP/s/W'),('area','Area efficiency','TFLOP/s/mm$^2$')]:
        output.append(r'\shortstack[l]{'+heading+r'\\('+unit+r')}'+' & '+' & '.join(cells[metric])+r' \\')
        if metric=='energy': output.append(r'\midrule')
    table = ROOT/'paper/tables/related_ppa.tex'
    text = table.read_text()
    text = replace_block(text, 'DP AREA CELLS', [r'\def\DPAreas{' + ' & '.join(profile_areas) + '}'])
    table.write_text(replace_block(text, 'EFFICIENCY ROWS', output))
    with (HERE/'table_efficiencies.csv').open('w') as stream:
        writer = csv.DictWriter(stream,fieldnames=list(rows[0]),lineterminator='\n')
        writer.writeheader(); writer.writerows(rows)
    metadata = dict(status='analytical_uncalibrated',
                    target='12 nm proxy (14 nm model for non-12-nm sources)',
                    scaling_rule='eta_A_target=eta_A_source*S_A*S_D; eta_E_target=eta_E_source*S_E; metric_target=metric_source/S_metric',
                    factors_to_proxy=factors,
                    assumptions=['Native 12 nm efficiencies unchanged', 'Delay-scaled frequency, no extra voltage scaling',
                                 'Missing source efficiency remains unavailable, not zero', 'Process normalization does not equalize libraries, temperature, activity or implementation stage'],
                    inputs=[dict(path=str(p.relative_to(ROOT)),sha256=hashlib.sha256(p.read_bytes()).hexdigest()) for p in (inputs_path,power_path,ROOT/inputs['tool_manifest'])],
                    rows=rows)
    (HERE/'table_efficiencies.json').write_text(json.dumps(metadata,indent=2)+'\n')
    for node, factor in factors.items(): print(node, 'to proxy:', factor)

if __name__=='__main__':
    main()
