#!/usr/bin/env python3
"""Derive DP-only K/N estimates from retained measurements; no new EDA runs."""
import csv
import hashlib
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent
AREA = ROOT / 'paper/data/DP_area_power/latest6_area.csv'
POWER = ROOT / 'paper/data/DP_area_power/latest6_power.csv'
FORMATS = [('H', 'bf16'), ('Q', 'mxfp8_e4m3'), ('E', 'mxfp4_e2m1')]
CONFIGS = [('1:2:6', 'dp_top_t8h16q32e96', 'dp_top_e64', 0.5),
           ('1:2:8', 'dp_top_t8h16q32e128', 'dp_top_e64', 1.0),
           ('1:4:8', 'dp_top_t8h16q64e128_opt', 'dp_top_q32e64', 1.0)]

def main():
    with AREA.open() as handle:
        area = {r['top']: float(r['area_um2']) for r in csv.DictReader(handle)}
    with POWER.open() as handle:
        power = {(r['top'], r['format']): float(r['total_mw']) for r in csv.DictReader(handle)}
    rows = []
    for ratio, expanded, dedicated, count in CONFIGS:
        row = {'ratio': ratio, 'k_top': expanded, 'n_added_top': dedicated,
               'n_added_per_baseline_dp': count, 'area_k_um2': area[expanded],
               'area_n_um2': area['dp_top'] + count * area[dedicated]}
        row['area_k_saving_pct'] = 100 * (1 - row['area_k_um2'] / row['area_n_um2'])
        for mode, fmt in FORMATS:
            key = (dedicated, fmt)
            # Only these explicitly unsupported mode/unit pairs receive ideal zero power.
            active = (dedicated == 'dp_top_q32e64' and mode in ('Q', 'E')) or mode == 'E'
            added_power = power[key] if active else 0.0
            row['power_k_' + mode + '_mw'] = power[(expanded, fmt)]
            row['power_n_' + mode + '_mw'] = power[('dp_top', fmt)] + count * added_power
            row['n_added_' + mode + '_active'] = active
            row['power_k_' + mode + '_saving_pct'] = 100 * (1 - row['power_k_' + mode + '_mw'] / row['power_n_' + mode + '_mw'])
        rows.append(row)
    metadata = {
        'model': 'DP-only area and mode-power sum, normalized per baseline DP',
        'normalization': 'N_base K-expanded DPs versus N_base baseline DPs plus alpha*N_base dedicated DPs; alpha=0.5 requires integer deployment (even columns for whole-column expansion)',
        'conditions': 'N12 TT, 0.7 V, 85 C, 1 GHz; measured BF16/MXFP8 E4M3/MXFP4 E2M1 total DP power',
        'inactive_n_dp': 'Ideal power gating: zero dynamic and leakage power; wake-up, retention, isolation and power-switch costs excluded',
        'area_boundary': 'Sum of DP standard-cell areas only; power gating does not remove physical DP area',
        'excluded': ['array storage', 'interconnect', 'non-DP logic', 'routing parasitics', 'power-gating overhead'],
        'comparison_limit': 'Standalone E64 and internal E components differ in pipeline partition and reduction implementation; not a composition-only ablation',
        'inputs': [{'path': str(p.relative_to(ROOT)), 'sha256': hashlib.sha256(p.read_bytes()).hexdigest()} for p in (AREA, POWER)],
        'rows': rows,
    }
    (HERE / 'kn_costs.json').write_text(json.dumps(metadata, indent=2) + '\n')
    with (HERE / 'kn_costs.csv').open('w') as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]), lineterminator='\n')
        writer.writeheader(); writer.writerows(rows)
    lines = [r'% Generated by paper/data/kn_comparison/calculate.py from retained DP measurements.',
             r'\begin{table}[t]', r'\centering',
             r'\caption{Modeled costs per baseline DP (K / N). Area: $10^3\,\mu$m$^2$; power: mW}',
             r'\label{tab:kn_costs}', r'\begingroup\footnotesize\setlength{\tabcolsep}{2pt}',
             r'\begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}lcccc@{}}\toprule',
             r'Ratio & Area (K / N) & $P_H$ (K / N) & $P_Q$ (K / N) & $P_E$ (K / N) \\\midrule']
    for row in rows:
        cells = [r'$' + row['ratio'] + '$', '{:.3f}/{:.3f}'.format(row['area_k_um2']/1000, row['area_n_um2']/1000)]
        cells += ['{:.3f}/{:.3f}'.format(row['power_k_'+m+'_mw'], row['power_n_'+m+'_mw']) for m,_ in FORMATS]
        lines.append(' & '.join(cells) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular*}\endgroup', r'\end{table}']
    (ROOT / 'paper/tables/kn_costs.tex').write_text('\n'.join(lines)+'\n')
    for row in rows:
        print(row['ratio'], 'area saving %', round(row['area_k_saving_pct'], 3),
              'power saving H/Q/E %', [round(row['power_k_'+m+'_saving_pct'],3) for m,_ in FORMATS])
if __name__ == '__main__':
    main()
